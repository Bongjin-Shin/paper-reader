import { test, expect } from '@playwright/test';
import { installBackend, open, wordBox, startPageTranslation } from './helpers';
for (const rotation of [0,90]) test(`Ctrl+F searches all pages and highlights the source at rotation ${rotation}`, async ({page}) => {
 await installBackend(page,{delay:0,fail:false,rotation,userUnit:1}); await open(page);
 await page.getByRole('button',{name:'본문 번역',exact:true}).click(); await startPageTranslation(page);
 await expect(page.locator('.translated-sentence')).toHaveCount(4);
 const translation=page.locator('.translation-content'), before=await translation.evaluate(e=>e.scrollTop);
 await page.keyboard.press('Control+f'); const input=page.getByRole('textbox',{name:'본문 검색어'});
 await expect(input).toBeFocused(); await input.fill('asymptotic');
 const status=page.getByRole('search',{name:'본문 내 찾기'}).getByRole('status'); await expect(status).toHaveText('1/4');
 const mark=page.locator('.pdf-page[data-page-number="1"] .pdf-search-mark.current'); await expect(mark).toHaveCount(1);
 const source=await wordBox(page), box=(await mark.boundingBox())!;
 expect(Math.abs(box.x-source.x)).toBeLessThan(2); expect(Math.abs(box.y-source.y)).toBeLessThan(2);
 expect(Math.abs(box.width-source.width)).toBeLessThan(2);
 await input.press('Enter'); await expect(status).toHaveText('2/4');
 await input.press('Enter'); await expect(status).toHaveText('3/4');
 await expect(page.locator('.pdf-page[data-page-number="2"] .pdf-search-mark.current')).toBeInViewport();
 expect(await translation.evaluate(e=>e.scrollTop)).toBe(before);
 await input.press('Shift+Enter'); await expect(status).toHaveText('2/4');
 await input.press('Shift+Enter'); await input.press('Shift+Enter'); await expect(status).toHaveText('4/4');
 await page.getByRole('button',{name:'확대',exact:true}).click();
 const second=await wordBox(page,'asymptotic',1,2), zoomed=(await page.locator('.pdf-search-mark.current').boundingBox())!;
 expect(Math.abs(second.x-zoomed.x)).toBeLessThan(2); expect(Math.abs(second.width-zoomed.width)).toBeLessThan(2);
 await input.fill('no-such-phrase'); await expect(status).toHaveText('검색 결과 없음'); await expect(page.locator('.pdf-search-mark')).toHaveCount(0);
 await input.press('Escape'); await expect(input).toHaveCount(0);
 expect(await page.evaluate(()=>(window as any).__calls.filter((c:any)=>c.command==='lookup_text'||c.command==='lookup_word').length)).toBe(0);
});
test('rapid changes cancel stale results and reopening find selects the retained query',async({page})=>{
 await installBackend(page); await open(page); await page.keyboard.press('Control+f');
 const input=page.getByRole('textbox',{name:'본문 검색어'}); await input.fill('model'); await input.fill('linear');
 await expect(page.getByRole('search').getByRole('status')).toHaveText('1/2');
 await page.keyboard.press('Escape'); await page.keyboard.press('Control+f');
 await expect(input).toHaveValue('linear'); await expect(input).toBeFocused();
 expect(await input.evaluate((e:HTMLInputElement)=>e.selectionEnd! - e.selectionStart!)).toBe(6);
 await expect(page.getByRole('search').getByRole('status')).toHaveText('1/2');
 await page.screenshot({path:'.tools/find-table-qa/find.png'});
});
test('opening another paper clears the query and does not navigate using the previous paper results',async({page})=>{
 await installBackend(page);await open(page);await page.keyboard.press('Control+f');
 await page.getByRole('textbox',{name:'본문 검색어'}).fill('asymptotic');
 await expect(page.getByRole('search').getByRole('status')).toHaveText('1/4');
 await page.getByRole('button',{name:'다음 검색 결과'}).click();
 await page.getByRole('button',{name:'다음 검색 결과'}).click();
 await expect(page.locator('.pdf-page[data-page-number="2"] .pdf-search-mark.current')).toBeInViewport();
 await page.evaluate(()=>{(window as any).__importPaths=['/papers/another-paper.pdf'];});
 await page.getByRole('button',{name:'PDF 열기',exact:true}).click();
 await expect(page.getByRole('search')).toHaveCount(0);await expect(page.locator('.pdf-search-mark')).toHaveCount(0);
 await expect.poll(()=>page.locator('.reader').evaluate(e=>e.scrollTop)).toBe(0);
 await page.keyboard.press('Control+f');await expect(page.getByRole('textbox',{name:'본문 검색어'})).toHaveValue('');
});
